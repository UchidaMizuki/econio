#' Convert byproduct transactions from the Stone method to the transfer method
#'
#' The Stone method records a byproduct as a negative input of the sector that
#' mainly produces it into the industry that generates it, e.g. scrap generated
#' by an industry. This function converts such negative intermediate
#' transactions between industries to the transfer method, which treats the
#' byproduct as sold by the generating industry to the main producing sector:
#' each negative transaction is set to zero, and its absolute value is added to
#' the reverse-direction cell. Negative transactions outside the inter-industry
#' block, e.g. byproducts generated by final demand sectors, are left unchanged.
#'
#' The transfer increases the intermediate demand of the sectors involved, and
#' so changes the import coefficients that [io_table_to_noncompetitive_import()]
#' uses to allocate imports. The result can therefore differ depending on
#' whether this function is called before or after that conversion.
#'
#' @param data An input-output table.
#'
#' @return An input-output table with negative intermediate transactions between
#' industries transferred to the corresponding reverse-direction cell.
#'
#' @export
io_table_transfer_byproduct <- function(data) {
  data <- io_check_axes(data)

  inter_industry <- io_inter_industry(data)
  dim_names <- dimnames(inter_industry)
  weight <- as.matrix(inter_industry)

  if (sum(weight < 0) == 0) {
    return(data)
  }

  weight <- pmax(weight, 0) + t(pmax(-weight, 0))
  inter_industry <- dibble::dibble(as.vector(weight), .dim_names = dim_names)

  data |>
    dplyr::rows_update(inter_industry)
}

#' Remove re-exports from an input-output table
#'
#' Treats the imports of each sector that exceed its regional demand
#' (intermediate plus final demand within the same region) as re-exports, i.e.
#' goods that are imported and then exported again, and subtracts them from
#' both the imports and the exports of the sector. The excess is split over the
#' import columns (e.g. imports and inflows) and the export columns (e.g.
#' exports and outflows) of the sector in proportion to their values.
#'
#' Total output and regional demand stay the same, and the import coefficient
#' of each such sector (see [io_import_coef()]) becomes 1, so that
#' [io_table_to_noncompetitive_import()] no longer makes its domestic
#' transactions negative. Re-exports can't exceed exports: if the excess is
#' larger than the exports of a sector, this removes all of its exports, warns,
#' and leaves its import coefficient above 1.
#'
#' Sectors whose imports are within their regional demand are left unchanged,
#' and so are sectors whose regional demand is not positive. The Stone method
#' lowers regional demand by recording byproducts as negative inputs, which
#' overstates the excess, so convert such byproducts with
#' [io_table_transfer_byproduct()] first.
#'
#' @param data A competitive import type input-output table.
#'
#' @return An input-output table with re-exports removed from its imports and
#' exports.
#'
#' @export
io_table_remove_reexport <- function(data) {
  if (!inherits(data, "io_table_competitive_import")) {
    cli::cli_abort(
      c(
        "{.arg data} must be a competitive import type input-output table.",
        "i" = "Re-exports can only be identified when imports are recorded by product."
      )
    )
  }

  excess <- io_import_excess(data)
  # Re-exports can't be identified without positive regional demand.
  is_excess <- excess$excess > 0 & excess$regional_demand > 0
  if (!any(is_excess)) {
    return(data)
  }

  over_export <- excess |>
    tibble::as_tibble() |>
    dplyr::filter(
      .data$regional_demand > 0,
      exceeds(.data$excess, .data$export)
    )
  if (!vctrs::vec_is_empty(over_export)) {
    cli::cli_warn(
      c(
        "Imports exceed regional demand by more than exports, so some import coefficients stay above 1.",
        glue::glue(
          "{io_axis_label(over_export$input)}: excess {signif(over_export$excess, 4)}, exports {signif(over_export$export, 4)}."
        ) |>
          rlang::set_names("x"),
        "i" = "Only up to the exports are removed as re-exports.",
        "i" = "This happens when output is negative, or when re-exports go to other regions within a multiregional table."
      )
    )
  }

  reexport <- dibble::ifelse(
    is_excess,
    pmax(pmin(excess$excess, excess$export), 0),
    0
  )
  import_scale <- 1 - safe_divide(reexport, excess$import)
  # Rounding can leave the re-exports slightly above the exports.
  export_scale <- pmax(1 - safe_divide(reexport, excess$export), 0)

  import <- data |>
    dplyr::filter(
      io_sector_type(.data$input) == "industry",
      io_sector_type(.data$output) == "import"
    )
  export <- data |>
    dplyr::filter(
      io_sector_type(.data$input) == "industry",
      io_sector_type(.data$output) == "export"
    )
  data |>
    dplyr::rows_update(
      dibble::broadcast(import * import_scale, dim_names = c("input", "output"))
    ) |>
    dplyr::rows_update(
      dibble::broadcast(export * export_scale, dim_names = c("input", "output"))
    )
}

# Imports, regional demand, the excess of imports over regional demand, and
# exports by industry of a competitive import type table, where regional demand
# is the intermediate and final demand within the same region.
io_import_excess <- function(data) {
  import <- -io_total_output(data, output_sector_type = "import")
  regional_demand <- io_total_output(
    data,
    output_sector_type = c("industry", "final_demand"),
    same_region = TRUE
  )
  dibble::dibble(
    import = import,
    regional_demand = regional_demand,
    excess = import - regional_demand,
    export = io_total_output(data, output_sector_type = "export")
  )
}
