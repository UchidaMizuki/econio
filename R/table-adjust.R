#' Convert byproduct transactions from the Stone method to the transfer method
#'
#' The Stone method records a byproduct as a negative input of the sector that
#' mainly produces it into the industry that generates it, e.g. scrap generated
#' by an industry. This function converts such negative intermediate
#' transactions between industries to the transfer method, which treats the
#' byproduct as sold by the generating industry to the main producing sector:
#' each negative transaction is set to zero, and its absolute value is added to
#' the reverse-direction cell. Negative transactions outside the inter-industry
#' block, e.g. byproducts generated by final demand sectors, are left unchanged.
#'
#' For a competitive import type table, call this after
#' [io_table_to_noncompetitive_import()] with `exclude_negative = TRUE` (and
#' [io_table_remove_reexport()] with the same `exclude_negative` before both). That conversion then treats negative transactions as domestic and
#' allocates imports to positive transactions only, so the negative domestic
#' transactions it leaves are exactly the byproducts. Transferring first would
#' turn the byproducts into positive transactions, which would then be given a
#' share of the imports although they are domestic.
#'
#' @param data An input-output table.
#'
#' @return An input-output table with negative intermediate transactions between
#' industries transferred to the corresponding reverse-direction cell.
#'
#' @export
io_table_transfer_byproduct <- function(data) {
  data <- io_check_axes(data)

  inter_industry <- io_inter_industry(data)
  # `t()` swaps the axes, which share their industries, so take back the
  # original axes to put each negative transaction in the reverse-direction
  # cell.
  byproduct <- t(dibble::pmax(-inter_industry, 0))
  dimnames(byproduct) <- dimnames(inter_industry)
  inter_industry <- dibble::pmax(inter_industry, 0) + byproduct

  data |>
    dplyr::rows_update(inter_industry)
}

#' Remove re-exports from an input-output table
#'
#' Treats the imports of each sector that exceed its regional demand as
#' re-exports, i.e. goods that are imported and then exported again, and
#' subtracts them from both the imports and the exports of the sector. The
#' excess is split over the import columns (e.g. imports and inflows) and the
#' export columns (e.g. exports and outflows) of the sector in proportion to
#' their values.
#'
#' Total output and regional demand stay the same, and the import coefficient
#' that [io_table_to_noncompetitive_import()] uses for each such sector becomes
#' 1, so that the conversion no longer makes its domestic transactions negative.
#' Re-exports can't exceed exports: if the excess is larger than the exports of
#' a sector, this removes all of its exports, warns, and leaves its import
#' coefficient above 1. Sectors whose imports are within their regional demand
#' are left unchanged. By default, so are sectors whose regional demand is zero
#' or negative, since their re-exports can't be identified. With
#' `exclude_negative = TRUE`, a sector without positive transactions has a
#' regional demand of zero, and all its imports are removed, up to its exports.
#'
#' Pass the same `exclude_negative` to [io_table_to_noncompetitive_import()].
#' Use `exclude_negative = TRUE` before [io_table_transfer_byproduct()], so that
#' the byproducts stay domestic.
#'
#' @param data A competitive import type input-output table.
#' @inheritParams io_regional_demand
#'
#' @return An input-output table with re-exports removed from its imports and
#' exports.
#'
#' @export
io_table_remove_reexport <- function(
  data,
  exclude_negative = FALSE
) {
  rlang::check_bool(exclude_negative)
  if (!inherits(data, "io_table_competitive_import")) {
    cli::cli_abort(
      c(
        "{.arg data} must be a competitive import type input-output table.",
        "i" = "Re-exports can only be identified when imports are recorded by product."
      )
    )
  }

  balance <- io_commodity_balance(data, exclude_negative = exclude_negative) |>
    dplyr::mutate(
      excess = .data$total_import - .data$total_regional_demand,
      # Re-exports are removed from the export columns only, which leave out the
      # shipments to the other regions of a multiregional table.
      export = io_total_output(data, output_sector_type = "export")
    )
  # Re-exports can't be identified from negative regional demand. Positive
  # regional demand of 0 means that all imports are re-exported.
  is_excess <- balance$excess > 0 &
    (balance$total_regional_demand > 0 | exclude_negative)

  over_export <- balance |>
    tibble::as_tibble() |>
    # Compare imports rather than the excess with a tolerance, since an excess
    # from rounding error alone can exceed exports of 0.
    dplyr::filter(
      .data$excess > 0,
      .data$total_regional_demand > 0 | .env$exclude_negative,
      exceeds(.data$total_import, .data$total_regional_demand + .data$export)
    )
  if (!vctrs::vec_is_empty(over_export)) {
    cli::cli_warn(
      c(
        "Imports exceed regional demand by more than exports, so some import coefficients stay above 1.",
        glue::glue(
          "{io_axis_label(over_export$input)}: excess {format_number(over_export$excess)}, exports {format_number(over_export$export)}."
        ) |>
          rlang::set_names("*"),
        "i" = "Only up to the exports are removed as re-exports."
      )
    )
  }

  reexport <- dibble::ifelse(
    is_excess,
    pmax(pmin(balance$excess, balance$export), 0),
    0
  )
  import_scale <- 1 - safe_divide(reexport, balance$total_import)
  export_scale <- 1 - safe_divide(reexport, balance$export)

  import <- data |>
    dplyr::filter(
      io_sector_type(.data$input) == "industry",
      io_sector_type(.data$output) == "import"
    )
  export <- data |>
    dplyr::filter(
      io_sector_type(.data$input) == "industry",
      io_sector_type(.data$output) == "export"
    )
  data |>
    dplyr::rows_update(
      dibble::broadcast(import * import_scale, dim_names = c("input", "output"))
    ) |>
    dplyr::rows_update(
      dibble::broadcast(export * export_scale, dim_names = c("input", "output"))
    )
}
